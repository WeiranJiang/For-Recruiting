// Turns drizzle-kit's generated SQL into an idempotent bootstrap script (src/lib/db/schema-sql.ts).
// Usage: npx drizzle-kit generate && node scripts/gen-schema-sql.mjs
import fs from "node:fs";
const files = fs.readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
let sql = files.map((f) => fs.readFileSync(`drizzle/${f}`, "utf8")).join("\n--> statement-breakpoint\n");
const stmts = sql.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean);
const out = [];
for (let s of stmts) {
  s = s.replace(/;$/, "");
  if (s.startsWith("CREATE TABLE")) out.push(s.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS") + ";");
  else if (s.startsWith("CREATE INDEX")) out.push(s.replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS") + ";");
  else if (s.startsWith("ALTER TABLE") && s.includes("ADD CONSTRAINT")) {
    const name = s.match(/ADD CONSTRAINT "([^"]+)"/)[1];
    out.push(`DO $$ BEGIN ${s}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
    void name;
  } else if (s.startsWith("ALTER TABLE") && s.includes("ADD COLUMN")) {
    out.push(s.replace("ADD COLUMN", "ADD COLUMN IF NOT EXISTS") + ";");
  } else out.push(s + ";");
}
// users must exist before tables referencing it (FKs are added after all tables anyway)
fs.writeFileSync(
  "src/lib/db/schema-sql.ts",
  `// GENERATED by scripts/gen-schema-sql.mjs — do not edit by hand.\nexport const SCHEMA_SQL = ${JSON.stringify(out.join("\n"))};\n`,
);
console.log(`wrote ${out.length} statements`);
